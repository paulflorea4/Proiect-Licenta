package com.gradingplatform.backend.service;

import com.gradingplatform.backend.ai.AiServiceClient;
import com.gradingplatform.backend.ai.FeedbackRequest;
import com.gradingplatform.backend.ai.FeedbackResponse;
import com.gradingplatform.backend.dto.HintResponse;
import com.gradingplatform.backend.dto.StudentSubmissionResponse;
import com.gradingplatform.backend.dto.StudentTestResultResponse;
import com.gradingplatform.backend.entity.AiFeedback;
import com.gradingplatform.backend.entity.Role;
import com.gradingplatform.backend.entity.SubmissionStatus;
import com.gradingplatform.backend.repository.AiFeedbackRepository;
import com.gradingplatform.backend.repository.AssignmentRepository;
import com.gradingplatform.backend.sandbox.TestOutcome;
import java.util.List;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Hints for a student's own graded submission (7.2a) with at least one test that did not pass
 * (7.2c): one level at a time, 1 then 2 then 3, each generated once by the AI service and stored
 * as an `ai_feedback` row.
 *
 * <p>{@link #requestNext} is deliberately not {@code @Transactional}: the reads and the insert each run in their own short
 * transaction, and the call to the AI service, which can take as long as its read timeout, happens
 * between them with no transaction open ({@link AiServiceClient} refuses otherwise). The grade is
 * never read for, or changed by, a hint.
 */
@Service
public class HintService {

    /** The highest level: a nudge, a pointer, a partial explanation. */
    public static final int MAX_LEVEL = 3;

    /** V10's `UNIQUE (submission_id, hint_level)`, under Postgres' default name. */
    static final String LEVEL_KEY = "ai_feedback_submission_id_hint_level_key";

    private final SubmissionViewService views;
    private final AssignmentRepository assignments;
    private final AiFeedbackRepository hints;
    private final AiServiceClient ai;

    public HintService(
            SubmissionViewService views,
            AssignmentRepository assignments,
            AiFeedbackRepository hints,
            AiServiceClient ai) {
        this.views = views;
        this.assignments = assignments;
        this.hints = hints;
        this.ai = ai;
    }

    /**
     * The hints a submission has received, level 1 first (7.2b), for whoever may read the submission:
     * its student, or the people who run its course. Same access rule as the submission itself
     * ({@link SubmissionViewService#view}); the caller picks the shape by role.
     *
     * @throws SubmissionNotFoundException if there is no such submission, or a teacher may not manage it
     * @throws AccessRefusedException if a student asks for another student's
     */
    @Transactional(readOnly = true)
    public List<AiFeedback> list(long userId, Role role, long submissionId) {
        views.view(userId, role, submissionId);
        return hints.findBySubmissionIdOrderByHintLevelAsc(submissionId);
    }

    /** A hint and whether this request stored it (201) rather than found or only showed it (200). */
    public record Outcome(HintResponse hint, boolean created) {}

    /**
     * The submission's next hint level, generated by the AI service from the student's own view of
     * the submission (7.1b) and stored. A fallback answer (6.4b) is returned but not stored, so the
     * same level is asked for again next time (the human's decision at 7.2a). When two requests ask
     * for the same level at once, the second finds the first's row through the unique constraint and
     * returns it.
     *
     * @throws SubmissionNotFoundException if there is no such submission
     * @throws AccessRefusedException if it is another student's (5.5a)
     * @throws HintNeedsGradedSubmissionException if it is not graded
     * @throws HintNothingToImproveException if every test passed, or it has none (7.2c): judged on
     *     the test results, not on the total, so a lost {@code MANUAL} mark does not make it eligible
     * @throws HintsUsedUpException if its three levels are used
     */
    public Outcome requestNext(long studentId, long submissionId) {
        StudentSubmissionResponse view =
                StudentSubmissionResponse.of(views.view(studentId, Role.STUDENT, submissionId));
        if (view.status() != SubmissionStatus.GRADED) {
            throw new HintNeedsGradedSubmissionException();
        }
        if (view.tests().stream().allMatch(HintService::passed)) {
            throw new HintNothingToImproveException();
        }
        int level = (int) hints.countBySubmissionId(submissionId) + 1;
        if (level > MAX_LEVEL) {
            throw new HintsUsedUpException();
        }
        String description = assignments
                .findById(view.assignmentId())
                .orElseThrow(SubmissionNotFoundException::new)
                .getDescription();

        FeedbackResponse answer = ai.feedback(FeedbackRequest.of(view, description, level));

        if (answer.fallback()) {
            return new Outcome(HintResponse.fallback(submissionId, level, answer.hint()), false);
        }
        try {
            AiFeedback stored = hints.saveAndFlush(new AiFeedback(submissionId, level, answer.hint()));
            return new Outcome(HintResponse.of(stored), true);
        } catch (DataIntegrityViolationException e) {
            if (!Constraints.isViolationOf(e, LEVEL_KEY)) {
                throw e;
            }
            // Another request stored this level while ours waited for the AI service: theirs counts.
            AiFeedback existing =
                    hints.findBySubmissionIdAndHintLevel(submissionId, level).orElseThrow(() -> e);
            return new Outcome(HintResponse.of(existing), false);
        }
    }

    /**
     * Whether a test passed, as the student's view shows it: a public test's outcome is {@code
     * PASSED}, a hidden test says {@code passed}. A test without a result did not pass.
     */
    private static boolean passed(StudentTestResultResponse test) {
        if (test instanceof StudentTestResultResponse.HiddenResult hidden) {
            return hidden.passed();
        }
        return ((StudentTestResultResponse.PublicResult) test).status() == TestOutcome.PASSED;
    }
}
